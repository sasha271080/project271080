/**
  ******************************************************************************
  * @file    mc_wifi.h
  * @brief   Мост телеметрии в Wi-Fi модуль ESP8266 (D1 mini) через USART3.
  *
  *  НАЗНАЧЕНИЕ: беспроводной дубль COM-порта. Модуль поднимает TCP-сервер,
  *  ПК или смартфон подключается к нему и получает тот же JSON, что идёт
  *  по USB. Команды управления идут в обратную сторону.
  *
  *  ПИНЫ: PB10 = USART3_TX -> RX модуля
  *        PB11 = USART3_RX <- TX модуля
  *  Выбраны намеренно далеко от PA8 (ШИМ) и PA6 (BKIN): USART1 на PA9/PA10
  *  сидел бы вплотную к выходу ШИМ.
  *
  *  СКОРОСТЬ 460800. Не «с запасом на будущее», а по расчёту: JSON-кадр
  *  до 712 байт каждые 40 мс = 178 кбит/с. На 115200 кадр физически не
  *  успевает уйти (62 мс против 40 мс) — буфер переполняется за секунды.
  *
  *  ПЕРЕДАЧА ЧЕРЕЗ DMA. Программная отправка 712 байт заняла бы 15 мс
  *  в главном цикле — это в 54 раза дольше периода контура тока (0.28 мс).
  *  DMA1_Channel2 (USART3_TX) свободен: АЦП занимает Channel1.
  ******************************************************************************
  */
#ifndef MC_WIFI_H
#define MC_WIFI_H

#include <stdint.h>

/* Скорость обмена с модулем. Менять только вместе с прошивкой ESP. */
#define WIFI_BAUD        460800u

/* Период кадра в Wi-Fi. 100000 = 10 кадров/с — хватает для наблюдения
   и втрое снижает нагрузку на канал по сравнению с USB (40000). */
#define WIFI_PERIOD_US   100000u

/* Размер приёмного кольца. Команды короткие, 256 байт с запасом. */
#define WIFI_RX_RING     256u

extern volatile uint8_t  wifi_enable;    /* WE1/WE0 — включить мост      */
extern volatile uint32_t wifi_tx_frames; /* отправлено кадров            */
extern volatile uint32_t wifi_tx_drops;  /* пропущено: DMA был занят     */
extern volatile uint32_t wifi_rx_cmds;   /* принято команд               */
extern volatile uint32_t wifi_last_rx_ms;/* когда последний раз отвечал  */

void mc_wifi_init(void);
void mc_wifi_task(void);                       /* из главного цикла */
uint8_t mc_wifi_send(const char *buf, uint16_t len);  /* 0 = занят */
uint8_t mc_wifi_online(void);                  /* связь жива */

#endif /* MC_WIFI_H */